#!/usr/bin/env python3
"""Build a canonical, event-centred role-aware network from AIDev event evidence.

The input is the known-only ``actor_pr_events.parquet`` file generated by the
AIDev preparation pipeline.  Each input row is retained as one event node and
is connected to its source account and pull request artifact. Repository
membership is stored as the PR node's ``repo_id`` attribute. The script is deliberately
streaming over the event parquet so that the resulting graph can be rebuilt on
an SSH host without materialising the full edge table in memory.

Outputs (under --out):
  nodes.parquet   account, pull_request/artifact and event nodes
  edges.parquet   participates_as and acts_on edges
  manifest.json   input/output hashes and deterministic counts

The input is expected to have complete identity labels upstream.  The
manifest records this assumption; the script refuses no rows, so it can also
be used for an audit run on another event table.
"""
from __future__ import annotations

import argparse
import collections
import hashlib
import json
import os
from pathlib import Path
from typing import Any, Dict, Iterable, Mapping, MutableMapping, Optional, Sequence

import pyarrow as pa
import pyarrow.parquet as pq


NODE_SCHEMA = pa.schema([
    ("node_id", pa.string()),
    ("node_type", pa.string()),
    ("label", pa.string()),
    ("actor_type", pa.string()),
    ("actor_subtype", pa.string()),
    ("repo_id", pa.int64()),
    ("pr_id", pa.int64()),
    ("relation", pa.string()),
    ("operation", pa.string()),
    ("role", pa.string()),
    ("event_time", pa.string()),
    ("agent", pa.string()),
    ("evidence_source", pa.string()),
])

EDGE_SCHEMA = pa.schema([
    ("edge_id", pa.string()),
    ("src_id", pa.string()),
    ("dst_id", pa.string()),
    ("edge_type", pa.string()),
    ("relation", pa.string()),
    ("operation", pa.string()),
    ("role", pa.string()),
    ("event_id", pa.string()),
    ("repo_id", pa.int64()),
    ("pr_id", pa.int64()),
    ("event_time", pa.string()),
    ("source_type", pa.string()),
    ("target_type", pa.string()),
    ("agent", pa.string()),
    ("evidence_source", pa.string()),
    ("weight", pa.int64()),
])

ROLE_MAP = {
    "author": "author",
    "agent_authored": "agent-label",
    "review": "reviewer",
    "review_comment": "review-commenter",
    "comment": "commenter",
    "commit_author": "commit-author",
    "commit_committer": "committer",
    "assignee": "assignee",
    "timeline_assigned": "assignee",
    "timeline_commented": "commenter",
    "timeline_committed": "committer",
    "timeline_labeled": "labeler",
    "timeline_merged": "merger",
    "timeline_review_requested": "review-requester",
    "timeline_review_request_removed": "review-request-remover",
    "timeline_unassigned": "unassigner",
    "timeline_copilot_work_started": "copilot-operator",
    "timeline_copilot_work_finished": "copilot-operator",
    "timeline_copilot_work_finished_failure": "copilot-operator",
}


def _nullable(v: Any) -> Optional[str]:
    if v is None:
        return None
    s = str(v)
    return s if s else None


def _hash_file(path: Path, chunk_size: int = 1024 * 1024) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        while True:
            b = f.read(chunk_size)
            if not b:
                break
            h.update(b)
    return h.hexdigest()


def _write_rows(writer: pq.ParquetWriter, rows: Sequence[Mapping[str, Any]], schema: pa.Schema) -> None:
    if not rows:
        return
    cols = {name: [row.get(name) for row in rows] for name in schema.names}
    writer.write_table(pa.Table.from_pydict(cols, schema=schema))


def _actor_key(source_node: str) -> str:
    # actor:id:123 -> id:123, while preserving virtual agent/service keys.
    return source_node[len("actor:") :] if source_node.startswith("actor:") else source_node


def _load_actor_labels(path: Optional[Path]) -> Dict[str, Dict[str, Optional[str]]]:
    if not path or not path.exists():
        return {}
    tab = pq.read_table(path, columns=["actor_key", "login", "actor_type", "actor_subtype"])
    out: Dict[str, Dict[str, Optional[str]]] = {}
    data = tab.to_pydict()
    for key, login, typ, sub in zip(data["actor_key"], data["login"], data["actor_type"], data["actor_subtype"]):
        out.setdefault(str(key), {"label": _nullable(login), "actor_type": _nullable(typ), "actor_subtype": _nullable(sub)})
    return out


def build(events_path: Path, out_dir: Path, actor_labels_path: Optional[Path], batch_size: int, max_rows: Optional[int]) -> Dict[str, Any]:
    out_dir.mkdir(parents=True, exist_ok=True)
    nodes_path = out_dir / "nodes.parquet"
    edges_path = out_dir / "edges.parquet"
    manifest_path = out_dir / "manifest.json"

    actor_labels = _load_actor_labels(actor_labels_path)
    pf = pq.ParquetFile(events_path)
    input_rows = int(pf.metadata.num_rows)
    if max_rows is not None:
        input_rows = min(input_rows, max_rows)

    # Metadata dictionaries are bounded by actors and PR artifacts, rather than
    # by the number of event rows. Event nodes themselves are streamed.
    accounts: Dict[str, Dict[str, Any]] = {}
    prs: Dict[str, Dict[str, Any]] = {}
    relation_counts: collections.Counter[str] = collections.Counter()
    source_type_counts: collections.Counter[str] = collections.Counter()
    event_counts: collections.Counter[str] = collections.Counter()
    node_counts: collections.Counter[str] = collections.Counter()
    edge_counts: collections.Counter[str] = collections.Counter()
    unknown_rows = 0
    event_rows = 0

    node_writer = pq.ParquetWriter(nodes_path, NODE_SCHEMA, compression="zstd")
    edge_writer = pq.ParquetWriter(edges_path, EDGE_SCHEMA, compression="zstd")
    try:
        rows_for_nodes: list[Dict[str, Any]] = []
        rows_for_edges: list[Dict[str, Any]] = []
        for batch in pf.iter_batches(batch_size=batch_size):
            data = batch.to_pydict()
            n = len(data["pr_id"])
            for i in range(n):
                if max_rows is not None and event_rows >= max_rows:
                    break
                event_rows += 1
                pr_id = int(data["pr_id"][i])
                repo_id = int(data["repo_id"][i])
                pr_node = _nullable(data["target_node"][i]) or f"pr:{pr_id}"
                src_node = _nullable(data["source_node"][i]) or ""
                src_type = _nullable(data["source_type"][i]) or "unknown"
                target_type = _nullable(data["target_type"][i]) or "pull_request"
                relation = _nullable(data["relation"][i]) or "unknown"
                operation = _nullable(data["event"][i]) or relation
                event_time = _nullable(data["event_time"][i])
                evidence = _nullable(data["evidence_source"][i])
                agent = _nullable(data["agent"][i])
                role = ROLE_MAP.get(relation, relation)
                if src_type == "unknown" or target_type == "unknown":
                    unknown_rows += 1
                relation_counts[relation] += 1
                source_type_counts[src_type] += 1
                event_counts[operation] += 1

                # Stable event identity is based on the canonical input row
                # order plus the input file hash recorded in the manifest.
                event_id = f"event:{event_rows - 1:012d}"
                rows_for_nodes.append({
                    "node_id": event_id,
                    "node_type": "event",
                    "label": None,
                    "actor_type": None,
                    "actor_subtype": None,
                    "repo_id": repo_id,
                    "pr_id": pr_id,
                    "relation": relation,
                    "operation": operation,
                    "role": role,
                    "event_time": event_time,
                    "agent": agent,
                    "evidence_source": evidence,
                })
                node_counts["event"] += 1

                if src_node:
                    meta = actor_labels.get(_actor_key(src_node), {})
                    acct = accounts.setdefault(src_node, {
                        "node_id": src_node,
                        "node_type": "account",
                        "label": meta.get("label"),
                        "actor_type": src_type,
                        "actor_subtype": meta.get("actor_subtype"),
                        "repo_id": None,
                        "pr_id": None,
                        "relation": None,
                        "operation": None,
                        "role": None,
                        "event_time": None,
                        "agent": None,
                        "evidence_source": meta.get("actor_type"),
                    })
                    if not acct.get("label") and meta.get("label"):
                        acct["label"] = meta["label"]
                    # Source type from event evidence takes priority over stale
                    # actor-label metadata when the actor is observed repeatedly.
                    acct["actor_type"] = src_type

                pr_meta = prs.setdefault(pr_node, {
                    "node_id": pr_node,
                    "node_type": "pull_request",
                    "label": None,
                    "actor_type": target_type,
                    "actor_subtype": None,
                    "repo_id": repo_id,
                    "pr_id": pr_id,
                    "relation": None,
                    "operation": None,
                    "role": None,
                    "event_time": None,
                    "agent": agent,
                    "evidence_source": None,
                })
                if not pr_meta.get("agent") and agent:
                    pr_meta["agent"] = agent
                # Typed edges retain the event role and provenance.  No edges
                # are inferred between accounts when another account is removed;
                # all projections are recomputed from these event records.
                rows_for_edges.extend([
                    {
                        "edge_id": f"edge:{event_rows - 1:012d}:account-event",
                        "src_id": src_node,
                        "dst_id": event_id,
                        "edge_type": "participates_as",
                        "relation": relation,
                        "operation": operation,
                        "role": role,
                        "event_id": event_id,
                        "repo_id": repo_id,
                        "pr_id": pr_id,
                        "event_time": event_time,
                        "source_type": src_type,
                        "target_type": "event",
                        "agent": agent,
                        "evidence_source": evidence,
                        "weight": 1,
                    },
                    {
                        "edge_id": f"edge:{event_rows - 1:012d}:event-pr",
                        "src_id": event_id,
                        "dst_id": pr_node,
                        "edge_type": "acts_on",
                        "relation": relation,
                        "operation": operation,
                        "role": role,
                        "event_id": event_id,
                        "repo_id": repo_id,
                        "pr_id": pr_id,
                        "event_time": event_time,
                        "source_type": "event",
                        "target_type": target_type,
                        "agent": agent,
                        "evidence_source": evidence,
                        "weight": 1,
                    },
                ])
                edge_counts["participates_as"] += 1
                edge_counts["acts_on"] += 1

                if len(rows_for_nodes) >= batch_size:
                    _write_rows(node_writer, rows_for_nodes, NODE_SCHEMA)
                    rows_for_nodes.clear()
                if len(rows_for_edges) >= batch_size * 2:
                    _write_rows(edge_writer, rows_for_edges, EDGE_SCHEMA)
                    rows_for_edges.clear()
            if max_rows is not None and event_rows >= max_rows:
                break
        _write_rows(node_writer, rows_for_nodes, NODE_SCHEMA)
        _write_rows(edge_writer, rows_for_edges, EDGE_SCHEMA)

        # Append bounded metadata nodes after streamed event nodes.
        _write_rows(node_writer, list(accounts.values()), NODE_SCHEMA)
        _write_rows(node_writer, list(prs.values()), NODE_SCHEMA)
        node_counts["account"] = len(accounts)
        node_counts["pull_request"] = len(prs)
    finally:
        node_writer.close()
        edge_writer.close()

    manifest = {
        "schema_version": "role-aware-network-v1",
        "built_by": "scripts/build_role_aware_network.py",
        "unknown_policy": "input_expected_known_only; unknown rows counted and retained for audit",
        "input": {
            "events": str(events_path),
            "actor_labels": str(actor_labels_path) if actor_labels_path else None,
            "rows": event_rows,
            "parquet_metadata_rows": int(pf.metadata.num_rows),
            "sha256": _hash_file(events_path),
        },
        "outputs": {
            "nodes": str(nodes_path),
            "edges": str(edges_path),
            "nodes_sha256": _hash_file(nodes_path),
            "edges_sha256": _hash_file(edges_path),
        },
        "network_schema": {
            "node_classes": ["account", "pull_request_artifact", "event"],
            "repository_representation": "repo_id attribute on pull_request_artifact nodes",
            "directed_edge_types": {
                "participates_as": "account -> event",
                "acts_on": "event -> pull_request_artifact",
            },
            "observation_edge_weight": 1,
        },
        "counts": {
            "nodes": dict(node_counts),
            "edges": dict(edge_counts),
            "relations": dict(relation_counts),
            "operations": dict(event_counts),
            "source_types": dict(source_type_counts),
            "unknown_rows": unknown_rows,
            "event_rows": event_rows,
            "account_nodes": len(accounts),
            "pull_request_nodes": len(prs),
        },
        "projection_note": "Projection is recomputed from event records. Removing account B does not create an inferred A-C edge; only an observed source-event-PR path retained by the projection is emitted.",
    }
    manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")
    return manifest


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--events", type=Path, default=Path("remote_results/filtered_known/actor_pr_events.parquet"))
    ap.add_argument("--actor-labels", type=Path, default=Path("remote_results/filtered_known/actor_labels.parquet"))
    ap.add_argument("--out", type=Path, default=Path("remote_results/role_aware_network"))
    ap.add_argument("--batch-size", type=int, default=50_000)
    ap.add_argument("--max-rows", type=int, default=None, help="debug option; build only the first N event rows")
    args = ap.parse_args()
    if not args.events.exists():
        raise SystemExit(f"events parquet not found: {args.events}")
    manifest = build(args.events, args.out, args.actor_labels if args.actor_labels.exists() else None, args.batch_size, args.max_rows)
    print(json.dumps(manifest["counts"], ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
